CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'citizen'
    CHECK (role IN ('citizen', 'admin')),
  notify_status boolean NOT NULL DEFAULT true,
  notify_crew boolean NOT NULL DEFAULT true,
  neighbourhood text NOT NULL DEFAULT 'Chikkamagaluru',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS notify_status boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS notify_crew boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS neighbourhood text NOT NULL DEFAULT 'Chikkamagaluru';

ALTER TABLE public.issues
  ADD COLUMN IF NOT EXISTS reporter_id uuid
    REFERENCES public.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS photo_url text,
  ADD COLUMN IF NOT EXISTS after_photo_url text,
  ADD COLUMN IF NOT EXISTS crew text,
  ADD COLUMN IF NOT EXISTS resolved_at timestamptz;

CREATE TABLE IF NOT EXISTS public.issue_upvotes (
  issue_id bigint NOT NULL
    REFERENCES public.issues(id) ON DELETE CASCADE,
  user_id uuid NOT NULL
    REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (issue_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL
    REFERENCES public.users(id) ON DELETE CASCADE,
  issue_id bigint
    REFERENCES public.issues(id) ON DELETE CASCADE,
  type text NOT NULL DEFAULT 'info',
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS issues_reporter_id_idx
  ON public.issues(reporter_id);

CREATE INDEX IF NOT EXISTS notifications_user_created_idx
  ON public.notifications(user_id, created_at DESC);